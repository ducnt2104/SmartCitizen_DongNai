const COS_LAT_SQUARED = Math.cos((11.35 * Math.PI) / 180) ** 2;

function clipPolygonByBisector(
  polyOpen: Array<[number, number]>,
  site: readonly [number, number],
  other: readonly [number, number],
): Array<[number, number]> {
  if (polyOpen.length < 3) return [];
  const dx = other[0] - site[0];
  const dy = other[1] - site[1];
  const mx = (site[0] + other[0]) / 2;
  const my = (site[1] + other[1]) / 2;
  const side = (p: readonly [number, number]): number => (p[0] - mx) * dx * COS_LAT_SQUARED + (p[1] - my) * dy;

  const out: Array<[number, number]> = [];
  for (let i = 0; i < polyOpen.length; i++) {
    const cur = polyOpen[i];
    const prev = polyOpen[(i + polyOpen.length - 1) % polyOpen.length];
    const sc = side(cur);
    const sp = side(prev);
    const inCur = sc <= 1e-12;
    const inPrev = sp <= 1e-12;
    if (inCur !== inPrev) {
      const t = sp / (sp - sc);
      out.push([prev[0] + t * (cur[0] - prev[0]), prev[1] + t * (cur[1] - prev[1])]);
    }
    if (inCur) out.push(cur);
  }

  const deduped: Array<[number, number]> = [];
  for (const pt of out) {
    const last = deduped[deduped.length - 1];
    if (!last || Math.hypot(pt[0] - last[0], pt[1] - last[1]) > 1e-7) {
      deduped.push(pt);
    }
  }
  if (deduped.length > 1 && Math.hypot(deduped[0][0] - deduped[deduped.length - 1][0], deduped[0][1] - deduped[deduped.length - 1][1]) <= 1e-7) {
    deduped.pop();
  }
  return deduped;
}

let cachedWardZones: GeoJSON.FeatureCollection<GeoJSON.Polygon> | null = null;

/**
 * Tạo lớp vùng 95 Đơn vị hành chính 2 cấp (33 Phường, 62 Xã) cắt khớp chính xác vào ranh giới thật
 * Thành phố Đồng Nai bằng phân hoạch Voronoi hiệu chỉnh theo vĩ độ trung tâm.
 */
export function buildDongNaiWardZonesGeoJson(): GeoJSON.FeatureCollection<GeoJSON.Polygon> {
  if (cachedWardZones) return cachedWardZones;

  const baseRingOpen: Array<[number, number]> = DONG_NAI_REAL_BOUNDARY_RING
    .slice(0, -1)
    .map(([lng, lat]) => [lng, lat]);
  const sites: Array<readonly [number, number]> = DONG_NAI_WARDS.map((w) => [w.centerLng, w.centerLat]);
  const features: Array<GeoJSON.Feature<GeoJSON.Polygon>> = [];

  for (let i = 0; i < DONG_NAI_WARDS.length; i++) {
    const ward = DONG_NAI_WARDS[i];
    let poly = baseRingOpen;
    for (let j = 0; j < sites.length; j++) {
      if (i !== j) {
        poly = clipPolygonByBisector(poly, sites[i], sites[j]);
        if (poly.length < 3) break;
      }
    }
    if (poly.length < 3) continue;

    const palette = REGION_PASTEL_PALETTE[ward.region];
    const shadeIdx = (i * 7 + ward.name.length) % palette.length;
    const closedRing = [...poly, [poly[0][0], poly[0][1]]];

    features.push({
      type: 'Feature',
      properties: {
        wardCode: ward.wardCode,
        name: ward.name,
        shortName: ward.shortName,
        kind: ward.kind,
        unitLabel: ward.kind,
        region: ward.region,
        zone: ward.zone,
        fillColor: palette[shadeIdx],
        borderColor: REGION_BORDER_COLOR[ward.region],
      },
      geometry: {
        type: 'Polygon',
        coordinates: [closedRing],
      },
    });
  }

  cachedWardZones = { type: 'FeatureCollection', features };
  return cachedWardZones;
}
